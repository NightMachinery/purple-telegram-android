package org.telegram.ui;
import java.io.File;
import java.util.*;
import org.telegram.messenger.purple.PurpleSearchRefresh;
import org.telegram.ui.ActionBar.BaseFragment;
import org.telegram.ui.Adapters.DialogsSearchAdapter;
import org.telegram.ui.Components.SearchViewPager;
public final class SearchRefreshCases {
    public static final List<String> events = new ArrayList<>();
    private static int checks;
    private static void same(Object got, Object expected) {
        checks++;
        if (!Objects.equals(got, expected)) throw new AssertionError("expected " + expected + " got " + got);
    }
    private static void refresh(PurpleDialogsHooks hooks, int account, SearchViewPager pager) {
        events.clear();
        hooks.refreshSearch(account, pager, true);
    }
    public static void main(String[] args) throws Exception {
        same(new File(PurpleSearchRefresh.class.getProtectionDomain().getCodeSource().getLocation().toURI()).getCanonicalFile(), new File(args[0]).getCanonicalFile());
        PurpleDialogsHooks screen = new PurpleDialogsHooks(new BaseFragment(2));
        DialogsSearchAdapter adapter = new DialogsSearchAdapter(2, null, true, true);
        SearchViewPager pager = new SearchViewPager(adapter);
        List<String> rawRecent = new ArrayList<>(adapter.rawRecent);
        List<String> rawHints = new ArrayList<>(adapter.rawHints);
        Map<String, Double> ratings = new LinkedHashMap<>(adapter.ratings);
        refresh(screen, 1, pager);
        same(events, Collections.emptyList());
        same(adapter.outerNotifies, 0);
        same(adapter.innerNotifies, 0);
        refresh(screen, 2, new SearchViewPager(new DialogsSearchAdapter(1, null, true, true)));
        same(events, Collections.emptyList());
        refresh(screen, 2, pager);
        same(events, Arrays.asList("filter", "outer", "inner"));
        same(adapter.recent, rawRecent);
        same(adapter.hints, rawHints);
        adapter.hidden.add("P");
        refresh(screen, 2, pager);
        same(adapter.recent, Arrays.asList("B", "P2", "A"));
        same(adapter.hints, Arrays.asList("B", "A", "P2"));
        same(adapter.outerNotifies, 2);
        same(adapter.innerNotifies, 2);
        adapter.hidden.clear();
        refresh(screen, 2, pager);
        same(adapter.recent, rawRecent);
        same(adapter.hints, rawHints);
        same(adapter.rawRecent, rawRecent);
        same(adapter.rawHints, rawHints);
        same(adapter.ratings, ratings);
        refresh(screen, 2, pager);
        same(adapter.recent, rawRecent);
        same(adapter.hints, rawHints);
        DialogsSearchAdapter typed = new DialogsSearchAdapter(2, "  P  ", true, true);
        refresh(screen, 2, new SearchViewPager(typed));
        same(typed.filteredQuery, "P");
        same(typed.recent, Arrays.asList("P", "P2"));
        typed.hidden.add("P2");
        refresh(screen, 2, new SearchViewPager(typed));
        same(typed.recent, Arrays.asList("P"));
        same(typed.hints, Arrays.asList("B", "P", "A"));
        refresh(screen, 2, null);
        same(events, Collections.emptyList());
        refresh(screen, 2, new SearchViewPager(null));
        same(events, Collections.emptyList());
        DialogsSearchAdapter noInner = new DialogsSearchAdapter(2, "", false, false);
        refresh(screen, 2, new SearchViewPager(noInner));
        same(events, Arrays.asList("filter", "outer"));
        same(noInner.recent, noInner.rawRecent);
        DialogsSearchAdapter noNestedAdapter = new DialogsSearchAdapter(2, null, true, false);
        refresh(screen, 2, new SearchViewPager(noNestedAdapter));
        same(events, Arrays.asList("filter", "outer"));
        same(noNestedAdapter.recent, noNestedAdapter.rawRecent);
        DialogsSearchAdapter retained = new DialogsSearchAdapter(2, null, true, true);
        SearchViewPager retainedPager = new SearchViewPager(retained);
        refresh(screen, 2, retainedPager);
        List<String> retainedRecent = new ArrayList<>(retained.rawRecent);
        List<String> retainedHints = new ArrayList<>(retained.rawHints);
        retained.hidden.add("P");
        retainedPager.setVisibility(android.view.View.GONE);
        events.clear();
        for (int i = 0; i < 100; ++i) screen.refreshSearch(2, retainedPager, false);
        same(events, Collections.emptyList());
        same(retained.outerNotifies, 1);
        same(retained.innerNotifies, 1);
        same(retained.recent, retainedRecent);
        same(retained.hints, retainedHints);
        retainedPager.setVisibility(android.view.View.VISIBLE);
        screen.refreshSearch(2, retainedPager, false);
        same(events, Collections.emptyList());
        same(retained.outerNotifies, 1);
        retainedPager.setVisibility(android.view.View.GONE);
        screen.refreshSearch(2, retainedPager, true);
        same(events, Collections.emptyList());
        retainedPager.setVisibility(android.view.View.INVISIBLE);
        screen.refreshSearch(2, retainedPager, true);
        same(events, Collections.emptyList());
        retainedPager.setVisibility(android.view.View.VISIBLE);
        refresh(screen, 2, retainedPager);
        same(events, Arrays.asList("filter", "outer", "inner"));
        same(retained.outerNotifies, 2);
        same(retained.innerNotifies, 2);
        same(retained.recent, Arrays.asList("B", "P2", "A"));
        same(retained.hints, Arrays.asList("B", "A", "P2"));
        retainedPager.setVisibility(android.view.View.GONE);
        retained.hidden.clear();
        events.clear();
        for (int i = 0; i < 100; ++i) screen.refreshSearch(2, retainedPager, false);
        same(events, Collections.emptyList());
        same(retained.outerNotifies, 2);
        same(retained.innerNotifies, 2);
        retainedPager.setVisibility(android.view.View.VISIBLE);
        refresh(screen, 2, retainedPager);
        same(retained.recent, retainedRecent);
        same(retained.hints, retainedHints);
        same(retained.rawRecent, retainedRecent);
        same(retained.rawHints, retainedHints);
        same(retained.ratings, ratings);
        System.out.println("SEARCH_REFRESH_CHECKS=" + checks);
    }
}
