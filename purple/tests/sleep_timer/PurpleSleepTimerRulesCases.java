package org.telegram.messenger.purple;

import static org.telegram.messenger.purple.PurpleSleepTimerRules.*;

public final class PurpleSleepTimerRulesCases {
    private static int checks;
    private static void check(boolean condition, String name) {
        checks++;
        if (!condition) throw new AssertionError(name);
    }
    private static Item item(int account, int message, Kind kind) {
        return new Item(account, 100, message, 1000 + message, kind);
    }
    private static PurpleSleepTimerRules music() {
        final PurpleSleepTimerRules rules = new PurpleSleepTimerRules();
        rules.loaded(Slot.AUDIO, item(0, 1, Kind.SONG), true);
        return rules;
    }
    public static void main(String[] args) {
        final PurpleSleepTimerRules empty = new PurpleSleepTimerRules();
        check(!empty.timed(10, MINUTE), "nothing loaded rejects duration");
        check(!empty.end(Slot.AUDIO), "nothing loaded rejects end");
        final PurpleSleepTimerRules rules = music();
        check(!rules.timed(0, MINUTE - 1), "minimum one minute");
        check(!rules.timed(0, MAX_DURATION + 1), "maximum twelve hours");
        check(rules.timed(100, MINUTE), "start paused or playing loaded item");
        check(!rules.due(60_099) && rules.due(60_100), "deadline inclusive");
        rules.manualPause(Slot.AUDIO);
        check(rules.remaining(30_100) == 30_000, "manual pause counts elapsed time");
        check(rules.add(30_100, 5 * MINUTE) && rules.remaining(30_100) == 330_000, "add from remaining");
        check(rules.add(30_100, MAX_DURATION) && rules.remaining(30_100) == MAX_DURATION, "add capped");
        check(!rules.add(30_100 + MAX_DURATION, MINUTE), "expired add cannot revive");
        rules.expire(null);
        check(rules.mode() == Mode.OFF, "expiry turns off");
        check(!rules.autoStart(rules.ticket(Slot.AUDIO)), "expiry fences even freshly captured automatic ticket");
        rules.manualPlay(Slot.AUDIO);
        final Ticket allowed = rules.ticket(Slot.AUDIO);
        check(rules.autoStart(allowed), "later explicit play works");
        rules.manualPause(Slot.AUDIO);
        check(!rules.autoStart(allowed), "explicit pause beats held-seek restoration");
        rules.manualPlay(Slot.AUDIO);
        final Ticket seekHold = rules.ticket(Slot.AUDIO);
        rules.seek(Slot.AUDIO);
        check(rules.autoStart(seekHold), "own seek pause does not become manual pause");
        check(rules.end(Slot.AUDIO), "bind end without duration");
        final long endGeneration = rules.generation();
        check(!rules.matchesEnd(Slot.AUDIO, seekHold, false, endGeneration), "near-end buffering is not real end");
        check(!rules.matchesEnd(Slot.AUDIO, seekHold, true, endGeneration - 1), "stale timer generation rejected");
        rules.end(Slot.AUDIO);
        check(!rules.matchesEnd(Slot.AUDIO, seekHold, true, endGeneration), "replaced timer rejects old queued end");
        final Item next = item(0, 2, Kind.SONG);
        rules.loaded(Slot.AUDIO, next, true);
        check(rules.mode() == Mode.END && !rules.matchesEnd(Slot.AUDIO, seekHold, true, rules.generation()), "manual switch rebinds and rejects old end");
        final Ticket newEnd = rules.ticket(Slot.AUDIO);
        check(rules.matchesEnd(Slot.AUDIO, newEnd, true, rules.generation()), "new bound item ends before repeat or traversal");
        rules.expire(next);
        check(rules.takePendingAdvance(next, false).equals(next), "song expiry schedules one manual next");
        check(rules.takePendingAdvance(next, false) == null, "manual next consumed once");
        rules.expire(next);
        rules.seek(Slot.AUDIO);
        check(rules.takePendingAdvance(next, false) == null, "seek clears pending next");
        rules.expire(next);
        check(rules.takePendingAdvance(next, true) == null && rules.takePendingAdvance(next, false) == null, "explicit item play clears pending next");
        rules.expire(item(0, 3, Kind.VOICE));
        check(rules.takePendingAdvance(next, false) == null, "voice never schedules next song");
        rules.manualPlay(Slot.AUDIO);
        rules.end(Slot.AUDIO);
        final Ticket transfer = rules.ticket(Slot.AUDIO);
        check(rules.handoff(transfer, Slot.VIEWER), "same item viewer handoff");
        check(rules.mode() == Mode.END && rules.current(Slot.AUDIO) == null, "handoff preserves end binding");
        check(!rules.unload(transfer), "old holder release cannot unload transferred item");
        check(rules.matchesEnd(Slot.VIEWER, rules.ticket(Slot.VIEWER), true, rules.generation()), "PiP shared item ends bound mode");
        rules.loaded(Slot.AUDIO, item(1, 2, Kind.SONG), true);
        rules.loaded(Slot.VIEWER, null, false);
        check(rules.mode() == Mode.OFF && rules.loaded(), "bound viewer loss cancels rather than binding other account song");
        rules.timed(0, MINUTE);
        rules.loaded(Slot.AUDIO, item(2, 2, Kind.SONG), true);
        check(rules.mode() == Mode.TIMED && rules.remaining(1000) == 59_000, "account switch preserves deadline");
        rules.loaded(Slot.AUDIO, null, false);
        check(rules.mode() == Mode.OFF, "nothing loaded cancels silently");
        check(new PurpleSleepTimerRules().mode() == Mode.OFF, "new process starts off");
        final PurpleSleepTimerRules recreated = music();
        final Ticket oldPlayer = recreated.ticket(Slot.AUDIO);
        recreated.replaceIncarnation(Slot.AUDIO);
        check(!recreated.autoStart(oldPlayer) && !recreated.unload(oldPlayer), "same item rebuilt player rejects old callback and unload");
        check(!item(0, 1, Kind.SONG).equals(item(1, 1, Kind.SONG)), "account belongs to identity");
        check(!new Item(0, 100, 1, 77, Kind.SONG).equals(new Item(0, 100, 1, 78, Kind.SONG)), "document belongs to identity");
        check(!new Item(0, 100, 1, 77, Kind.SONG).equals(new Item(0, 101, 1, 77, Kind.SONG)), "dialog belongs to identity");
        recreated.loaded(Slot.AUDIO, item(0, 3, Kind.VOICE), true);
        recreated.end(Slot.AUDIO);
        recreated.loaded(Slot.AUDIO, item(0, 1, Kind.SONG), true);
        check(recreated.mode() == Mode.OFF, "voice loss never rebinds unrelated saved song");
        final PurpleSleepTimerRules dispatch = music();
        dispatch.end(Slot.AUDIO);
        final EndEvent oldEnd = dispatch.captureEnd(Slot.AUDIO);
        dispatch.end(Slot.AUDIO);
        check(!dispatch.matchesEnd(oldEnd, true), "captured old event cannot consume newer same-item timer");
        check(dispatch.mode() == Mode.END, "new timer survives stale callback");
        final EndEvent freshEnd = dispatch.captureEnd(Slot.AUDIO);
        check(!dispatch.matchesEnd(freshEnd, false), "library-delivered old end rejected when actual native player is ready");
        check(dispatch.matchesEnd(freshEnd, true), "current native true end consumes current generation");
        dispatch.replaceIncarnation(Slot.AUDIO);
        check(!dispatch.matchesEnd(freshEnd, true), "old raw-player incarnation rejected");
        dispatch.cancel();
        check(!dispatch.matchesEnd(dispatch.captureEnd(Slot.AUDIO), true), "off timer cannot consume end");
        final PurpleSleepTimerRules controls = music();
        final Ticket automaticBefore = controls.ticket(Slot.AUDIO);
        controls.expire(null);
        check(!controls.transport(Slot.AUDIO, true, false, automaticBefore), "automatic session start stays fenced after expiry");
        check(!controls.transport(Slot.AUDIO, true, false, controls.ticket(Slot.AUDIO)), "capturing fresh automatic ticket cannot release expiry fence");
        check(controls.transport(Slot.AUDIO, false, false, controls.ticket(Slot.AUDIO)), "automatic stash pause is permitted");
        check(controls.blocked(Slot.AUDIO), "automatic pause never releases fence");
        check(controls.transport(Slot.AUDIO, true, true, controls.ticket(Slot.AUDIO)), "controller request explicitly plays after expiry");
        check(!controls.blocked(Slot.AUDIO), "explicit play grants new intent");
        final Ticket heldSeek = controls.ticket(Slot.AUDIO);
        controls.seek(Slot.AUDIO);
        check(controls.autoStart(heldSeek), "seek-owned pause retains its original intent");
        controls.transport(Slot.AUDIO, false, true, heldSeek);
        check(!controls.autoStart(heldSeek), "controller Pause defeats held seek auto resume");
        controls.seek(Slot.AUDIO);
        check(!controls.autoStart(controls.ticket(Slot.AUDIO)), "seek cannot release deliberate Pause");
        controls.transport(Slot.AUDIO, true, true, controls.ticket(Slot.AUDIO));
        check(controls.autoStart(controls.ticket(Slot.AUDIO)), "later hardware style explicit Play remains ordinary");
        final PurpleSleepTimerSavedSong.Selection selection = new PurpleSleepTimerSavedSong.Selection(
                item(0, 1, Kind.SONG), .375f, 12_345, 12);
        final int[] adoption = {0};
        final PurpleSleepTimerSavedSong.Selection[] heldSelection = {null};
        check(PurpleSleepTimerSavedSong.restore(selection, item(0, 1, Kind.SONG), value -> {
            adoption[0]++;
            heldSelection[0] = value;
        }), "saved song restores selected paused model");
        check(adoption[0] == 1 && heldSelection[0] == selection, "model adoption happens exactly once without a preparation port");
        check(heldSelection[0].progressMs == 12_345 && heldSelection[0].progressSec == 12, "saved positions preserved exactly");
        check(Float.floatToIntBits(heldSelection[0].progress) == Float.floatToIntBits(.375f), "saved fractional seek preserved exactly");
        check(!PurpleSleepTimerSavedSong.restore(selection, item(1, 1, Kind.SONG), value -> adoption[0]++), "other account selection rejected");
        check(!PurpleSleepTimerSavedSong.restore(selection, item(0, 2, Kind.SONG), value -> adoption[0]++), "other selected song rejected without queue movement");
        check(!PurpleSleepTimerSavedSong.restore(null, item(0, 1, Kind.SONG), value -> adoption[0]++), "no saved music keeps ordinary voice finish");
        check(!PurpleSleepTimerSavedSong.restore(selection, null, value -> adoption[0]++), "missing selection does not prepare fallback");
        check(adoption[0] == 1, "rejected saved selections have no model side effect");
        final PurpleSleepTimerRules heldRules = music();
        heldRules.expire(null);
        heldRules.loaded(Slot.AUDIO, selection.item, true);
        check(heldRules.blocked(Slot.AUDIO), "paused model restoration does not grant automatic intent");
        check(!heldRules.autoStart(heldRules.ticket(Slot.AUDIO)), "saved restored model cannot autoplay");
        heldRules.transport(Slot.AUDIO, true, true, heldRules.ticket(Slot.AUDIO));
        check(heldRules.autoStart(heldRules.ticket(Slot.AUDIO)), "explicit Play permits later stock preparation of held song");
        final Object gallery = new Object();
        final PurpleSleepTimerViewerIdentity identities = new PurpleSleepTimerViewerIdentity();
        final Item local = identities.item(Source.LOCAL_VIEWER, gallery);
        check(local.source == Source.LOCAL_VIEWER && local.localId > 0, "gallery has typed process-local identity");
        check(identities.item(Source.LOCAL_VIEWER, gallery) == local, "same gallery selection survives quality rebuild");
        check(new PurpleSleepTimerViewerIdentity().item(Source.LOCAL_VIEWER, gallery) == local, "same source retains identity across viewer holder transfer");
        check(!identities.item(Source.EMBED, gallery).equals(local), "embed and gallery identity namespaces differ");
        check(!identities.item(Source.LOCAL_VIEWER, new Object()).equals(local), "manual gallery selection changes identity");
        check(identities.item(Source.LOCAL_VIEWER, null) == null, "no synthetic identity without an actual source owner");
        check(!local.equals(new Item(0, 0, 0, 0, Kind.VIDEO)), "local token is not a fabricated message identity");
        final Object equalA = new String("same");
        final Object equalB = new String("same");
        check(!identities.item(Source.LOCAL_VIEWER, equalA).equals(identities.item(Source.LOCAL_VIEWER, equalB)), "source object identity cannot collapse equal-valued selections");
        final PurpleSleepTimerRules galleryRules = new PurpleSleepTimerRules();
        galleryRules.loaded(Slot.VIEWER, local, true);
        check(galleryRules.timed(0, MINUTE), "gallery alone counts as loaded media");
        galleryRules.expire(null);
        check(!galleryRules.autoStart(galleryRules.ticket(Slot.VIEWER)), "gallery expiry fences native PiP automatic resume");
        galleryRules.transport(Slot.VIEWER, true, true, galleryRules.ticket(Slot.VIEWER));
        check(galleryRules.autoStart(galleryRules.ticket(Slot.VIEWER)), "explicit gallery PiP Play works after expiry");
        galleryRules.end(Slot.VIEWER);
        final EndEvent galleryEnd = galleryRules.captureEnd(Slot.VIEWER);
        galleryRules.replaceIncarnation(Slot.VIEWER);
        check(!galleryRules.matchesEnd(galleryEnd, true), "old gallery native end cannot consume rebuilt same-item timer");
        final Item secondGallery = identities.item(Source.LOCAL_VIEWER, new Object());
        galleryRules.loaded(Slot.VIEWER, secondGallery, true);
        check(galleryRules.mode() == Mode.END && galleryRules.boundItem().equals(secondGallery), "manual gallery selection rebinds end timer");
        check(galleryRules.matchesEnd(galleryRules.captureEnd(Slot.VIEWER), true), "gallery ends only on actual backend end");
        final Item embed = identities.item(Source.EMBED, new Object());
        galleryRules.loaded(Slot.VIEWER, embed, true);
        final EndEvent oldEmbed = galleryRules.captureEnd(Slot.VIEWER);
        galleryRules.end(Slot.VIEWER);
        check(!galleryRules.matchesEnd(oldEmbed, true), "queued embed end cannot consume replacement timer");
        check(!galleryRules.matchesEnd(galleryRules.captureEnd(Slot.VIEWER), false), "embed near-end position is not a backend completion signal");
        galleryRules.loaded(Slot.VIEWER, null, false);
        check(galleryRules.mode() == Mode.OFF, "loss or retirement of bound embed cancels timer");
        final PurpleSleepTimerSavedSong.Retirement retirement = new PurpleSleepTimerSavedSong.Retirement();
        final Object oldVoicePlayer = new Object();
        final Object[] nativeOwner = {oldVoicePlayer};
        final java.util.ArrayList<String> order = new java.util.ArrayList<>();
        final PurpleSleepTimerRules retirementRules = new PurpleSleepTimerRules();
        retirementRules.loaded(Slot.AUDIO, item(0, 20, Kind.VOICE), true);
        retirementRules.expire(null);
        final Ticket retiringVoice = retirementRules.ticket(Slot.AUDIO);
        check(retirement.run(true, () -> {
            check(retirement.active(), "cleanup recursion guard is active during actual retirement callback");
            check(!retirement.run(true, () -> order.add("recursive"), () -> false), "nested cleanup does not restore recursively");
            nativeOwner[0] = null;
            retirementRules.unload(retiringVoice);
            order.add("retired");
        }, () -> PurpleSleepTimerSavedSong.restore(selection, selection.item, state -> {
            check(nativeOwner[0] == null, "saved selection adopted only after native ownership is cleared");
            retirementRules.loaded(Slot.AUDIO, state.item, true);
            order.add("adopted");
        })), "blocked close handles retirement and model restoration once");
        check(order.equals(java.util.Arrays.asList("retired", "adopted")), "normal cleanup precedes model adoption");
        check(!retirement.active(), "cleanup recursion guard clears after restoration");
        check(!retirementRules.autoStart(retiringVoice), "retired voice callback cannot target restored song");
        check(!retirementRules.autoStart(retirementRules.ticket(Slot.AUDIO)), "restored song stays paused with automatic intent fenced");
        retirementRules.transport(Slot.AUDIO, true, true, retirementRules.ticket(Slot.AUDIO));
        if (nativeOwner[0] == null) { nativeOwner[0] = new Object(); order.add("prepared-song"); }
        check(nativeOwner[0] != oldVoicePlayer && order.get(2).equals("prepared-song"), "later explicit song Play prepares new ownership rather than resuming old voice");
        check(!retirement.run(false, () -> order.add("wrong"), () -> true), "ordinary unrelated cleanup stays stock");
        final boolean[] adoptedAfterFailure = {false};
        try {
            retirement.run(true, () -> { throw new IllegalStateException("sentinel retirement failure"); }, () -> { adoptedAfterFailure[0] = true; return true; });
            check(false, "retirement failure must propagate");
        } catch (IllegalStateException expected) {
            check(!retirement.active() && !adoptedAfterFailure[0], "failed retirement cannot adopt a model and releases recursion guard");
        }
        final PurpleSleepTimerViewerSelection selectionGate = new PurpleSleepTimerViewerSelection();
        final Item displayed = item(0, 40, Kind.VIDEO);
        final PurpleSleepTimerRules indexRules = new PurpleSleepTimerRules();
        indexRules.loaded(Slot.VIEWER, displayed, true);
        check(!selectionGate.select(displayed, PurpleSleepTimerViewerSelection.Origin.REFRESH), "initial automatic observation grants no Play");
        indexRules.expire(null);
        final Ticket expiredCollection = indexRules.ticket(Slot.VIEWER);
        for (int numericIndex : new int[]{-1, 0, 9, 2}) {
            final Item rebuiltSameMessage = item(0, 40, Kind.VIDEO);
            check(!selectionGate.select(rebuiltSameMessage, PurpleSleepTimerViewerSelection.Origin.REFRESH), "same logical message reindex grants no Play at index " + numericIndex);
            indexRules.loaded(Slot.VIEWER, rebuiltSameMessage, true);
            check(!indexRules.autoStart(indexRules.ticket(Slot.VIEWER)), "PiP expansion remains fenced after automatic collection reset " + numericIndex);
        }
        check(!selectionGate.select(displayed, PurpleSleepTimerViewerSelection.Origin.USER_SELECTION), "selecting same displayed item is not explicit Play");
        indexRules.manualPlay(Slot.VIEWER);
        check(indexRules.autoStart(indexRules.ticket(Slot.VIEWER)), "deliberate Play on same item recovers from expiry");
        final Ticket beforeManualPause = indexRules.ticket(Slot.VIEWER);
        indexRules.manualPause(Slot.VIEWER);
        check(!selectionGate.select(item(0, 40, Kind.VIDEO), PurpleSleepTimerViewerSelection.Origin.REFRESH)
                && indexRules.blocked(Slot.VIEWER) && !indexRules.autoStart(beforeManualPause), "automatic refresh cannot release deliberate Pause");
        indexRules.manualPlay(Slot.VIEWER);
        check(!selectionGate.select(item(0, 40, Kind.VIDEO), PurpleSleepTimerViewerSelection.Origin.REFRESH)
                && indexRules.autoStart(indexRules.ticket(Slot.VIEWER)), "ordinary active playback survives automatic reindex");
        final Item userSameIndexNewItem = item(0, 41, Kind.VIDEO);
        check(selectionGate.select(userSameIndexNewItem, PurpleSleepTimerViewerSelection.Origin.USER_SELECTION), "actual user item change grants Play even at same numeric index");
        indexRules.manualPlay(Slot.VIEWER);
        indexRules.loaded(Slot.VIEWER, userSameIndexNewItem, true);
        check(indexRules.autoStart(indexRules.ticket(Slot.VIEWER)) && !indexRules.valid(expiredCollection), "manual new item plays and old collection callback stays stale");
        indexRules.end(Slot.VIEWER);
        final EndEvent priorUserEnd = indexRules.captureEnd(Slot.VIEWER);
        final Item nextUserItem = item(0, 42, Kind.VIDEO);
        check(selectionGate.select(nextUserItem, PurpleSleepTimerViewerSelection.Origin.USER_SELECTION), "real next-item selection remains manual");
        indexRules.manualPlay(Slot.VIEWER);
        indexRules.loaded(Slot.VIEWER, nextUserItem, true);
        check(indexRules.mode() == Mode.END && indexRules.boundItem().equals(nextUserItem)
                && !indexRules.matchesEnd(priorUserEnd, true), "manual item switch retains end rebind and rejects old end");
        indexRules.expire(null);
        final Item automaticDifferentItem = item(0, 43, Kind.VIDEO);
        check(!selectionGate.select(automaticDifferentItem, PurpleSleepTimerViewerSelection.Origin.REFRESH), "automatic collection replacement is not manual even for a different item");
        indexRules.loaded(Slot.VIEWER, automaticDifferentItem, true);
        check(indexRules.blocked(Slot.VIEWER) && !indexRules.autoStart(indexRules.ticket(Slot.VIEWER)), "automatic different item cannot unlock expansion");
        check(!selectionGate.select(null, PurpleSleepTimerViewerSelection.Origin.USER_SELECTION), "invalid target creates no intent");
        check(!selectionGate.select(automaticDifferentItem, PurpleSleepTimerViewerSelection.Origin.USER_SELECTION), "invalid target did not forget displayed logical identity");
        final PurpleSleepTimerViewerSelection gallerySelection = new PurpleSleepTimerViewerSelection();
        check(gallerySelection.select(local, PurpleSleepTimerViewerSelection.Origin.USER_SELECTION), "actual first gallery open can play");
        check(!gallerySelection.select(identities.item(Source.LOCAL_VIEWER, gallery), PurpleSleepTimerViewerSelection.Origin.REFRESH), "gallery quality or reindex retains same logical source");
        check(gallerySelection.select(secondGallery, PurpleSleepTimerViewerSelection.Origin.USER_SELECTION), "different gallery source at same slot is manual");
        check(!gallerySelection.select(local, PurpleSleepTimerViewerSelection.Origin.REFRESH), "automatic setter keeps REFRESH origin even within a user-open caller stack");
        check(!indexRules.autoStart(expiredCollection), "old automatic callback cannot gain authority after later selections");
        final PurpleSleepTimerViewerSelection reopenGate = new PurpleSleepTimerViewerSelection();
        final PurpleSleepTimerRules reopenRules = new PurpleSleepTimerRules();
        check(!reopenGate.select(displayed, PurpleSleepTimerViewerSelection.Origin.REFRESH), "saved logical selection initially observed without Play");
        reopenRules.loaded(Slot.VIEWER, displayed, true);
        reopenRules.expire(null);
        final Ticket beforeClose = reopenRules.ticket(Slot.VIEWER);
        reopenRules.unload(beforeClose);
        check(reopenRules.current(Slot.VIEWER) == null && reopenRules.blocked(Slot.VIEWER), "normal close retains expired fence rather than globally clearing it");
        check(reopenGate.select(item(0, 40, Kind.VIDEO), PurpleSleepTimerViewerSelection.Origin.USER_OPEN), "verified actual user reopening same logical message grants Play");
        reopenRules.manualPlay(Slot.VIEWER);
        reopenRules.loaded(Slot.VIEWER, displayed, true);
        check(reopenRules.autoStart(reopenRules.ticket(Slot.VIEWER)) && !reopenRules.valid(beforeClose), "same-item user reopen permits stock preparation but rejects old native receipt");
        reopenRules.manualPause(Slot.VIEWER);
        check(!reopenGate.select(item(0, 40, Kind.VIDEO), PurpleSleepTimerViewerSelection.Origin.REFRESH)
                && reopenRules.blocked(Slot.VIEWER), "SavedState restore remains REFRESH and cannot release Pause");
        check(!reopenGate.select(displayed, PurpleSleepTimerViewerSelection.Origin.USER_SELECTION)
                && reopenRules.blocked(Slot.VIEWER), "same-item thumbnail remains distinct from actual user open");
        check(reopenGate.select(displayed, PurpleSleepTimerViewerSelection.Origin.USER_OPEN), "actual same-item user open also releases deliberate Pause when caller grants intent");
        reopenRules.manualPlay(Slot.VIEWER);
        check(reopenRules.autoStart(reopenRules.ticket(Slot.VIEWER)), "normal reopen does not need a redundant Play press");
        final Ticket priorReopen = reopenRules.ticket(Slot.VIEWER);
        final Item otherOpened = item(0, 44, Kind.VIDEO);
        check(reopenGate.select(otherOpened, PurpleSleepTimerViewerSelection.Origin.USER_OPEN), "different-item actual user open preserves autoplay intent");
        reopenRules.manualPlay(Slot.VIEWER);
        reopenRules.loaded(Slot.VIEWER, otherOpened, true);
        check(reopenRules.autoStart(reopenRules.ticket(Slot.VIEWER)) && !reopenRules.valid(priorReopen), "new opening invalidates previous item's receipt");
        reopenRules.manualPause(Slot.VIEWER);
        check(!reopenRules.autoStart(beforeClose) && !reopenRules.autoStart(priorReopen), "stale callbacks from before close or prior open cannot resume");
        check(!reopenGate.select(null, PurpleSleepTimerViewerSelection.Origin.USER_OPEN), "invalid opening target cannot fabricate intent");
        final PurpleSleepTimerViewerSelection galleryOpen = new PurpleSleepTimerViewerSelection();
        check(!galleryOpen.select(local, PurpleSleepTimerViewerSelection.Origin.REFRESH), "gallery restore alone remains automatic");
        check(galleryOpen.select(local, PurpleSleepTimerViewerSelection.Origin.USER_OPEN), "actual same-gallery source reopening has explicit opening intent");
        System.out.println("SLEEP_TIMER_RULES=" + checks);
    }
}
